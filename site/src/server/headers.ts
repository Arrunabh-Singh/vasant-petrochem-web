/**
 * The site's security headers, in one place: scripts/prepare.mjs writes them
 * to public/_headers for the static files, and src/middleware.ts adds them to
 * the Worker's own responses (the enquiry endpoints, the offers board).
 *
 * VP-SEC-002: production enforces the baseline policy while the strict one
 * runs report-only to /api/csp-report; after a week without violations the
 * strict policy becomes the enforced one. The pages carry no inline script or
 * style (JSON-LD is data, not script), so the strict policy needs no
 * 'unsafe-inline' and no hashes.
 */
const TURNSTILE = "https://challenges.cloudflare.com";
// Cloudflare Web Analytics, when the owner switches it on: cookieless, no personal data.
const ANALYTICS = "https://static.cloudflareinsights.com";
const BEACON = "https://cloudflareinsights.com";

export function contentSecurityPolicy(strict: boolean): string {
  return [
    "default-src 'self'",
    `script-src 'self' ${TURNSTILE} ${ANALYTICS} ${strict ? "'inline-speculation-rules'" : "'unsafe-inline'"}`,
    `style-src 'self'${strict ? "" : " 'unsafe-inline'"}`,
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src 'self' ${TURNSTILE} ${BEACON}`,
    `frame-src ${TURNSTILE}`,
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(strict ? ["require-trusted-types-for 'script'", "report-uri /api/csp-report", "report-to csp"] : []),
  ].join("; ");
}

export const securityHeaders: Readonly<Record<string, string>> = {
  // VP-SEC-001, unchanged from the hub. Listing on hstspreload.org stays the owner's decision.
  "Strict-Transport-Security": "max-age=63072000; includeSubDomains; preload",
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "DENY",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "accelerometer=(), browsing-topics=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()",
  "Cross-Origin-Opener-Policy": "same-origin",
  "Content-Security-Policy": contentSecurityPolicy(false),
  "Content-Security-Policy-Report-Only": contentSecurityPolicy(true),
  "Reporting-Endpoints": 'csp="/api/csp-report"',
};

/**
 * The Worker's own responses (the endpoints and the offers board) are never
 * embedded by other sites. Static files leave CORP out: the logo and share
 * images are meant to load in email signatures and link previews.
 */
export const workerHeaders: Readonly<Record<string, string>> = { ...securityHeaders, "Cross-Origin-Resource-Policy": "same-origin" };

/** Long caching for files that change rarely; /_astro/* (hashed names) is set immutable by the adapter. */
export const cacheRules: Readonly<Record<string, string>> = {
  "/fonts/*": "public, max-age=2592000",
  "/brand/*": "public, max-age=86400",
  "/og/*": "public, max-age=86400",
};

/** The Cloudflare _headers file for the static files. */
export function headersFile(): string {
  const block = (path: string, headers: Record<string, string>) => [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join("\n");
  return [
    "# Generated by scripts/prepare.mjs from src/server/headers.ts. Do not edit.",
    block("/*", securityHeaders),
    ...Object.entries(cacheRules).map(([path, value]) => block(path, { "Cache-Control": value })),
    "",
  ].join("\n");
}
